// The screenshot dimensions, read off the files themselves.
//
// Two things need them and neither can guess: the browser needs width/height on the <img>
// to reserve the box before the bytes arrive, and the stylesheet needs the intrinsic width
// as a ceiling so a 480x196 tooltip is not stretched across a 1030px column — which is what
// the site did until this existed, and it read as a blurry screenshot rather than as a small
// one.
//
// Generated rather than typed, because a hand-kept table of twenty pairs of numbers is a
// second list that goes stale the first time a screenshot is retaken at a new size. The
// build runs this before tsc, so a retaken shot is picked up by rebuilding and a renamed one
// fails the type-check rather than shipping a 404 behind a reserved box.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const siteDir = join(here, "..");
const shotsDir = join(siteDir, "public", "shots");
const outPath = join(siteDir, "src", "lib", "shots.generated.ts");

const PNG_SIGNATURE = "89504e470d0a1a0a";

/** width and height out of a PNG's IHDR, which is always the first chunk. */
function pngSize(buf, name) {
  if (buf.subarray(0, 8).toString("hex") !== PNG_SIGNATURE) {
    throw new Error(`shots: ${name} is not a PNG`);
  }
  if (buf.subarray(12, 16).toString("ascii") !== "IHDR") {
    throw new Error(`shots: ${name} has no IHDR where one must be`);
  }
  return [buf.readUInt32BE(16), buf.readUInt32BE(20)];
}

const files = readdirSync(shotsDir)
  .filter((n) => n.endsWith(".png"))
  .sort();

if (files.length === 0) {
  throw new Error("shots: public/shots holds no PNG — the pages reference screenshots");
}

const rows = files.map((name) => {
  const [w, h] = pngSize(readFileSync(join(shotsDir, name)), name);
  // keyed by the URL a page writes, so a lookup is the same string the <img> carries
  return `  "/claude-tray/shots/${name}": [${w}, ${h}],`;
});

const banner = `// GENERATED by scripts/shots.mjs — do not edit. Run \`npm run generate\`.
//
// The intrinsic size of every screenshot in public/shots, keyed by the URL a page
// references it with. Read by lib/shots.ts, which is what the <img> width/height and the
// no-upscale ceiling come from.
`;

writeFileSync(
  outPath,
  `${banner}\nexport const SHOT_SIZES: Record<string, readonly [number, number]> = {\n${rows.join("\n")}\n};\n`,
);

console.log(`shots: ${files.length} screenshot(s) -> src/lib/shots.generated.ts`);
